def _fold_merged_proposals() -> None:
    """Before merged_into goes, copy each merged proposal's ratings (max stars per
    person) and hosts onto its root, as the old code did at read time. Otherwise the
    root silently loses interest and hosts."""
    bind = op.get_bind()
    parent = dict(bind.execute(sa.text("SELECT id, merged_into FROM proposals")).all())

    def root(pid: int) -> int:
        seen: set[int] = set()
        while parent.get(pid) is not None and pid not in seen:
            seen.add(pid)
            pid = parent[pid]
        return pid

    for child, merged_into in parent.items():
        if merged_into is None:
            continue
        r = root(child)
        for u, stars in bind.execute(sa.text(
                "SELECT participant_id, stars FROM ratings WHERE proposal_id = :c"),
                {"c": child}).all():
            have = bind.execute(sa.text(
                "SELECT stars FROM ratings WHERE proposal_id = :r AND participant_id = :u"),
                {"r": r, "u": u}).scalar()
            if have is None:
                bind.execute(sa.text(
                    "INSERT INTO ratings (participant_id, proposal_id, stars, updated_at) "
                    "VALUES (:u, :r, :s, CURRENT_TIMESTAMP)"), {"u": u, "r": r, "s": stars})
            elif stars > have:
                bind.execute(sa.text(
                    "UPDATE ratings SET stars = :s WHERE proposal_id = :r AND participant_id = :u"),
                    {"u": u, "r": r, "s": stars})
        bind.execute(sa.text(
            "INSERT OR IGNORE INTO proposal_runners (proposal_id, participant_id) "
            "SELECT :r, participant_id FROM proposal_runners WHERE proposal_id = :c"),
            {"r": r, "c": child})


